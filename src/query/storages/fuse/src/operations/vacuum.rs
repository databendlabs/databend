/// Object storage supported by Databend is expected to return entries sorted in ascending lexicographical
/// order by object key. Databend leverages this property to enhance the efficiency and thoroughness
/// of the vacuum process.
///
/// The safety of the vacuum algorithm does not depend on this ordering.
async fn general_list_until_prefix(
    dal: &Operator,
    path: &str,
    until: &str,
    need_one_more: bool,
    gc_root_meta_ts: Option<DateTime<Utc>>,
) -> Result<Vec<Entry>> {
    let mut lister = dal.lister(path).await?;
    let mut paths = vec![];
    while let Some(entry) = lister.try_next().await? {
        if entry.metadata().is_dir() {
            continue;
        }
        if entry.path() >= until {
            info!("entry path: {} >= until: {}", entry.path(), until);
            if need_one_more {
                paths.push(entry);
            }
            break;
        }
        if gc_root_meta_ts.is_none()
            || is_gc_candidate_segment_block(&entry, dal, gc_root_meta_ts.unwrap()).await?
        {
            paths.push(entry);
        }
    }
    Ok(paths)
}

/// If storage is backed by FS, we prioritize thoroughness over efficiency (though efficiency loss
/// is usually not significant). All entries are fetched and sorted before extracting the prefix entries.
async fn fs_list_until_prefix(
    dal: &Operator,
    path: &str,
    until: &str,
    need_one_more: bool,
    gc_root_meta_ts: Option<DateTime<Utc>>,
) -> Result<Vec<Entry>> {
    // Fetch ALL entries from the path and sort them by path in lexicographical order.
    let mut lister = dal.lister(path).await?;
    let mut entries = Vec::new();
    while let Some(item) = lister.try_next().await? {
        if item.metadata().is_file() {
            entries.push(item);
        }
    }
    entries.sort_by(|l, r| l.path().cmp(r.path()));

    // Extract entries up to the `until` path, respecting lexicographical order.
    let mut res = Vec::new();
    for entry in entries {
        if entry.path() >= until {
            info!("entry path: {} >= until: {}", entry.path(), until);
            if need_one_more {
                res.push(entry);
            }
            break;
        }
        if gc_root_meta_ts.is_none()
            || is_gc_candidate_segment_block(&entry, dal, gc_root_meta_ts.unwrap()).await?
        {
            res.push(entry);
        }
    }

    Ok(res)
}

/// Check if an entry is a candidate for garbage collection
pub async fn is_gc_candidate_segment_block(
    entry: &Entry,
    op: &Operator,
    gc_root_meta_ts: DateTime<Utc>,
) -> Result<bool> {
    let path = entry.path();
    let last_part = path.rsplit('/').next().unwrap();
    if last_part.starts_with(VACUUM2_OBJECT_KEY_PREFIX) {
        return Ok(true);
    }
    let last_modified = if let Some(v) = entry.metadata().last_modified() {
        v
    } else {
        let path = entry.path();
        let meta = op.stat(path).await?;
        meta.last_modified().ok_or_else(|| {
            ErrorCode::StorageOther(format!(
                "Failed to get `last_modified` metadata of the entry '{}'",
                path
            ))
        })?
    };
    let last_modified = DateTime::<Utc>::from(SystemTime::from(last_modified));
    Ok(last_modified + ASSUMPTION_MAX_TXN_DURATION < gc_root_meta_ts)
}

impl FuseTable {
    /// Protect live table-tag references from VACUUM2 and remove expired tags.
    pub async fn protect_table_tag_references(
        &self,
        catalog: &Arc<dyn Catalog>,
        root_snapshot_location: &str,
        snapshot_files_to_gc: &mut Vec<String>,
        protected_segments: &mut HashSet<Location>,
    ) -> Result<()> {
        let now = Utc::now();
        let tags = catalog
            .list_table_tags(ListTableTagsReq {
                table_id: self.get_id(),
                include_expired: true,
            })
            .await?;

        let mut protected_snapshot_locs = HashSet::new();
        for (tag_name, seq_tag) in tags {
            if seq_tag
                .data
                .expire_at
                .is_some_and(|expire_at| expire_at <= now)
            {
                if let Err(error) = catalog
                    .drop_table_tag(DropTableTagReq {
                        table_id: self.get_id(),
                        tag_name,
                        seq: Some(seq_tag.seq),
                    })
                    .await
                {
                    warn!(
                        "drop expired tag failed, ignored, table: {}, err: {}",
                        self.table_info.desc, error
                    );
                }
                continue;
            }

            let tag_snapshot_loc = seq_tag.data.snapshot_loc;
            if tag_snapshot_loc.as_str() < root_snapshot_location {
                if let Some(snapshot) =
                    SnapshotsIO::read_snapshot_for_vacuum(self.get_operator(), &tag_snapshot_loc)
                        .await?
                {
                    protected_segments.extend(snapshot.segments.iter().cloned());
                }
                protected_snapshot_locs.insert(tag_snapshot_loc);
            }
        }

        snapshot_files_to_gc.retain(|path| !protected_snapshot_locs.contains(path));
        Ok(())
    }

    pub async fn vacuum_table(
        &self,
        ctx: Arc<dyn TableContext>,
        vacuum_handler: &VacuumHandlerWrapper,
        respect_flash_back: bool,
    ) {
        warn!(
            "Vacuuming table: {}, ident: {}",
            self.table_info.name, self.table_info.ident
        );

        if let Err(e) = vacuum_handler
            .do_vacuum2(self, ctx, respect_flash_back)
            .await
        {
            // Vacuum in a best-effort manner, errors are ignored
            warn!("Vacuum table {} failed : {}", self.table_info.name, e);
        } else {
            info!("Vacuum table {} done", self.table_info.name);
        }
    }

    pub fn vacuum2_until_prefix(path: &str, until: DateTime<Utc>) -> String {
        let uuid = uuid_from_date_time(until);
        let uuid_str = uuid.simple().to_string();

        // extract the most significant 48 bits, which is 12 characters
        let timestamp_component = &uuid_str[..12];
        format!(
            "{}{}{}",
            path, VACUUM2_OBJECT_KEY_PREFIX, timestamp_component
        )
    }

    /// List files until a specific timestamp
    ///
    /// This implementation uses UUID v7 timestamp extraction for precise filtering.
    /// Used by vacuum2.
    pub async fn list_files_until_timestamp(
        &self,
        path: &str,
        until: DateTime<Utc>,
        need_one_more: bool,
        gc_root_meta_ts: Option<DateTime<Utc>>,
    ) -> Result<Vec<Entry>> {
        let until = Self::vacuum2_until_prefix(path, until);
        self.list_files_until_prefix(path, &until, need_one_more, gc_root_meta_ts)
            .await
    }

    /// List files until a specific location/prefix
    ///
    /// This implementation handles different storage schemes (FS vs object storage) and
    /// includes gc_root_meta_ts checking for safe vacuum operations.
    pub async fn list_files_until_prefix(
        &self,
        path: &str,
        until: &str,
        need_one_more: bool,
        gc_root_meta_ts: Option<DateTime<Utc>>,
    ) -> Result<Vec<Entry>> {
        info!("Listing files until prefix: {}", until);
        let dal = self.get_operator_ref();

        match dal.info().scheme() {
            "fs" => fs_list_until_prefix(dal, path, until, need_one_more, gc_root_meta_ts).await,
            _ => general_list_until_prefix(dal, path, until, need_one_more, gc_root_meta_ts).await,
        }
    }

    /// Collect the segments that are still recoverable from a table's head.
    ///
    /// Unlike the old prefix scan, this follows the committed `prev_snapshot_id` chain and stops
    /// at the table's earliest retained GC root. Snapshot objects older than that root cannot be
    /// reached by time travel and therefore must not keep owner data alive indefinitely.
    async fn collect_retained_snapshot_segments<T>(
        table: &FuseTable,
        ctx: &Arc<dyn TableContext>,
        snapshot_location: String,
        segments: &mut HashSet<Location>,
        status_callback: &T,
    ) -> Result<()>
    where
        T: Fn(String),
    {
        let retention_policy = table.get_data_retention_policy(ctx.as_ref())?;
        let reader = MetaReaders::table_snapshot_reader(table.get_operator());
        let location_generator = table.meta_location_generator();
        let mut location = snapshot_location;
        let mut version = TableMetaLocationGenerator::snapshot_version(&location);
        let start = Instant::now();
        let mut count = 0;
        let mut time_boundary = None;

        loop {
            let snapshot = reader
                .read(&LoadParams {
                    location: location.clone(),
                    len_hint: None,
                    ver: version,
                    put_cache: true,
                })
                .await
                .map_err(|err| {
                    err.with_context(format!(
                        "failed to protect clone table {} snapshot {}",
                        table.get_id(),
                        location
                    ))
                })?;
            let timestamp = snapshot.timestamp.ok_or_else(|| {
                ErrorCode::Internal(format!(
                    "clone table {} snapshot {} has no timestamp",
                    table.get_id(),
                    location
                ))
            })?;

            if count == 0 {
                if let RetentionPolicy::ByTimePeriod(retention) = retention_policy {
                    // Match `navigate_for_purge`: the boundary is relative to this member's head,
                    // not wall-clock time. The first snapshot at or before it is retained.
                    time_boundary = Some(timestamp - retention);
                }
            }

            segments.extend(snapshot.segments.iter().cloned());
            count += 1;
            let reached_retention_root = match retention_policy {
                RetentionPolicy::ByTimePeriod(_) => {
                    timestamp <= time_boundary.expect("initialized from the head snapshot")
                }
                RetentionPolicy::ByNumOfSnapshotsToKeep(limit) => count >= limit.max(1),
            };
            if reached_retention_root {
                break;
            }

            let Some((previous_id, previous_version)) = snapshot.prev_snapshot_id else {
                break;
            };
            location = location_generator
                .gen_snapshot_location(&previous_id, previous_version)
                .map_err(|err| {
                    err.with_context(format!(
                        "failed to locate clone table {} previous snapshot {}",
                        table.get_id(),
                        previous_id
                    ))
                })?;
            version = previous_version;
        }

        let status = format!(
            "gc clone refs: table {}, retained snapshots: {}, protected segments: {}, cost: {:?}",
            table.get_id(),
            count,
            segments.len(),
            start.elapsed()
        );
        info!("{}", status);
        (status_callback)(status);
        Ok(())
    }

    /// Select the oldest snapshot needed to cover both this clone's retention window and every
    /// snapshot that can still be made visible under this table's LVT.
    async fn select_clone_descendant_protection_root<T>(
        table: &FuseTable,
        ctx: &Arc<dyn TableContext>,
        snapshot_location: String,
        table_lvt: Option<DateTime<Utc>>,
        status_callback: &T,
    ) -> Result<(Arc<TableSnapshot>, LeastVisibleTime)>
    where
        T: Fn(String),
    {
        let retention_policy = table.get_data_retention_policy(ctx.as_ref())?;
        let reader = MetaReaders::table_snapshot_reader(table.get_operator());
        let location_generator = table.meta_location_generator();
        let start = Instant::now();
        let mut location = snapshot_location;
        let version = TableMetaLocationGenerator::snapshot_version(&location);
        let mut snapshot = reader
            .read(&LoadParams {
                location: location.clone(),
                len_hint: None,
                ver: version,
                put_cache: true,
            })
            .await?;
        let head_timestamp = snapshot.timestamp.ok_or_else(|| {
            ErrorCode::Internal(format!(
                "clone table {} snapshot {} has no timestamp",
                table.get_id(),
                location
            ))
        })?;
        let time_boundary = match retention_policy {
            RetentionPolicy::ByTimePeriod(retention) => Some(head_timestamp - retention),
            RetentionPolicy::ByNumOfSnapshotsToKeep(_) => None,
        };
        let mut count = 1;
        let mut retention_lvt = None;
        let mut lvt_boundary_reached = table_lvt.is_none_or(|lvt| head_timestamp <= lvt);

        // Immutable snapshots point to predecessors. Normal commits create new IDs, CLONE
        // starts a new chain, and FLASHBACK only moves the head; none introduces a cycle.
        loop {
            let timestamp = snapshot.timestamp.ok_or_else(|| {
                ErrorCode::Internal(format!(
                    "clone table {} snapshot {} has no timestamp",
                    table.get_id(),
                    location
                ))
            })?;
            let retention_root_reached = match retention_policy {
                RetentionPolicy::ByTimePeriod(_) => {
                    timestamp <= time_boundary.expect("set for time retention")
                }
                RetentionPolicy::ByNumOfSnapshotsToKeep(limit) => count >= limit.max(1),
            };
            if retention_root_reached && retention_lvt.is_none() {
                retention_lvt = Some(LeastVisibleTime::new(timestamp));
            }
            if retention_root_reached && lvt_boundary_reached {
                break;
            }

            let Some((previous_id, previous_version)) = snapshot.prev_snapshot_id else {
                break;
            };
            let previous_location = location_generator
                .gen_snapshot_location(&previous_id, previous_version)
                .map_err(|err| {
                    err.with_context(format!(
                        "failed to locate clone table {} previous snapshot {}",
                        table.get_id(),
                        previous_id
                    ))
                })?;
            let previous = match reader
                .read(&LoadParams {
                    location: previous_location.clone(),
                    len_hint: None,
                    ver: previous_version,
                    put_cache: true,
                })
                .await
            {
                Ok(previous) => previous,
                Err(err) if err.code() == ErrorCode::STORAGE_NOT_FOUND => {
                    warn!(
                        "stop clone protection at the earliest readable snapshot, table: {}, missing previous snapshot: {}",
                        table.get_id(),
                        previous_location
                    );
                    break;
                }
                Err(err) => {
                    return Err(err.with_context(format!(
                        "failed to protect clone table {} snapshot {}",
                        table.get_id(),
                        previous_location
                    )));
                }
            };

            if !lvt_boundary_reached {
                let previous_timestamp = previous.timestamp.ok_or_else(|| {
                    ErrorCode::Internal(format!(
                        "clone table {} snapshot {} has no timestamp",
                        table.get_id(),
                        previous_location
                    ))
                })?;
                if table_lvt.is_some_and(|lvt| previous_timestamp < lvt) && retention_root_reached {
                    break;
                }
                lvt_boundary_reached = table_lvt.is_some_and(|lvt| previous_timestamp <= lvt);
            }

            location = previous_location;
            snapshot = previous;
            count += 1;
        }

        let status = format!(
            "gc clone refs: table {}, inspected snapshots: {}, protection root: {}, root segments: {}, cost: {:?}",
            table.get_id(),
            count,
            location,
            snapshot.segments.len(),
            start.elapsed()
        );
        info!("{}", status);
        (status_callback)(status);
        let retention_lvt = retention_lvt.unwrap_or_else(|| {
            LeastVisibleTime::new(snapshot.timestamp.expect("validated while traversing"))
        });
        Ok((snapshot, retention_lvt))
    }

    async fn protect_table_tags(
        table: &FuseTable,
        catalog: &Arc<dyn Catalog>,
        segments: &mut HashSet<Location>,
    ) -> Result<()> {
        let tags = catalog
            .list_table_tags(ListTableTagsReq {
                table_id: table.get_id(),
                include_expired: false,
            })
            .await?;
        for (_tag_name, seq_tag) in tags {
            // Tag listing and object reads are not atomic. A listed tag may be dropped or
            // expire before this read, allowing another GC to remove its snapshot. Tolerate
            // NotFound without revalidating the tag: this scan is not a strongly consistent
            // tag view. Other storage errors still abort GC.
            if let Some(snapshot) = SnapshotsIO::read_snapshot_for_vacuum(
                table.get_operator(),
                &seq_tag.data.snapshot_loc,
            )
            .await?
            {
                segments.extend(snapshot.segments.iter().cloned());
            }
        }
        Ok(())
    }

    fn clone_descendant_ids(
        clone_group_id: u64,
        source_table_id: u64,
        bindings: &[(u64, u64)],
    ) -> Result<HashSet<u64>> {
        let clone_ids = bindings
            .iter()
            .map(|(table_id, _)| *table_id)
            .collect::<HashSet<_>>();
        let mut children = HashMap::<u64, Vec<u64>>::new();
        for (table_id, source_id) in bindings {
            children.entry(*source_id).or_default().push(*table_id);
        }

        let descendants_of = |root| {
            let mut queue = VecDeque::from([root]);
            let mut descendants = HashSet::new();
            while let Some(source_id) = queue.pop_front() {
                if let Some(child_ids) = children.get(&source_id) {
                    for child_id in child_ids {
                        if descendants.insert(*child_id) {
                            queue.push_back(*child_id);
                        }
                    }
                }
            }
            descendants
        };

        // A malformed or disconnected lineage can hide a live member from descendant protection.
        // Validate the entire binding graph using IDs only and fail closed before reading metadata.
        let connected = descendants_of(clone_group_id);
        if connected != clone_ids || connected.contains(&clone_group_id) {
            return Err(ErrorCode::Internal(format!(
                "clone group {} has malformed or disconnected lineage",
                clone_group_id
            )));
        }

        Ok(if source_table_id == clone_group_id {
            connected
        } else {
            descendants_of(source_table_id)
        })
    }

    /// Extend the mark set with live or recoverable descendants of this table.
    ///
    /// Clone references only flow from a source to its descendants. Siblings and ancestors cannot
    /// acquire files created by this table after their own clone point, so they do not participate
    /// in this table owner's mark phase. This marks snapshot roots only: callers must separately
    /// collect descendant tags after LVT publication (or after this scan for non-publishing paths).
    #[async_backtrace::framed]
    pub async fn extend_clone_descendant_referenced_segments<T>(
        &self,
        ctx: Arc<dyn TableContext>,
        segments: &mut HashSet<Location>,
        status_callback: T,
    ) -> Result<(HashSet<u64>, HashMap<u64, LeastVisibleTime>)>
    where
        T: Fn(String),
    {
        let catalog = ctx.get_catalog(self.get_table_info().catalog()).await?;
        let clone_group_id = self.clone_group_id()?;
        let bindings = catalog.list_clone_group_bindings(clone_group_id).await?;
        let descendant_ids = Self::clone_descendant_ids(clone_group_id, self.get_id(), &bindings)?;
        let descendants = catalog
            .mget_table_metas_by_ids(&descendant_ids.iter().copied().collect::<Vec<_>>())
            .await?;

        let mut table_lvts = HashMap::with_capacity(descendants.len());
        for (table_id, seq_meta) in descendants {
            let Some(seq_meta) = seq_meta else {
                continue;
            };
            let mut table_info = self.get_table_info().clone();
            table_info.ident.table_id = table_id;
            table_info.ident.seq = seq_meta.seq;
            table_info.meta = seq_meta.data;
            let descendant = catalog.get_table_by_info(&table_info)?;
            let descendant = FuseTable::try_from_table(descendant.as_ref())?;

            if let Some(snapshot_location) = descendant.snapshot_loc() {
                let table_lvt = catalog
                    .get_table_lvt(&LeastVisibleTimeIdent::new(ctx.get_tenant(), table_id))
                    .await?
                    .map(|lvt| lvt.time);
                let (protection_root, retention_lvt) =
                    Self::select_clone_descendant_protection_root(
                        descendant,
                        &ctx,
                        snapshot_location,
                        table_lvt,
                        &status_callback,
                    )
                    .await?;
                segments.extend(protection_root.segments.iter().cloned());
                table_lvts.insert(table_id, retention_lvt);
                continue;
            }

            let statistics = &descendant.get_table_info().meta.statistics;
            let is_empty = statistics.number_of_rows == 0
                && statistics.data_bytes == 0
                && statistics.compressed_data_bytes == 0
                && statistics.number_of_segments.unwrap_or(0) == 0
                && statistics.number_of_blocks.unwrap_or(0) == 0;
            if !is_empty {
                return Err(ErrorCode::Internal(format!(
                    "non-empty clone descendant {} has no snapshot location",
                    table_id
                )));
            }
        }
        Ok((descendant_ids, table_lvts))
    }

    /// Re-read lineage after publishing LVTs. A clone committed before publication is not fenced
    /// by the new source LVT, so any newly observed descendant must abort this sweep. Clones that
    /// begin after publication are fenced by the source LVT in their create transaction.
    ///
    /// TODO: This does not detect an existing member's FLASHBACK committed between mark and LVT
    /// publication. Its historical head can invalidate the mark or fall below the new LVT.
    /// Use a GC-specific generation or a post-publication re-mark to close this known window;
    /// do not CAS the long-lived TableMeta seq, which also conflicts with normal forward commits.
    pub async fn has_new_clone_descendants(
        &self,
        ctx: &Arc<dyn TableContext>,
        observed_descendants: &HashSet<u64>,
    ) -> Result<bool> {
        let catalog = ctx.get_catalog(self.get_table_info().catalog()).await?;
        let clone_group_id = self.clone_group_id()?;
        let bindings = catalog.list_clone_group_bindings(clone_group_id).await?;
        let current_descendants =
            Self::clone_descendant_ids(clone_group_id, self.get_id(), &bindings)?;
        Ok(!current_descendants.is_subset(observed_descendants))
    }

    pub async fn extend_clone_descendant_tag_segments(
        &self,
        ctx: Arc<dyn TableContext>,
        descendant_ids: &HashSet<u64>,
        segments: &mut HashSet<Location>,
    ) -> Result<()> {
        let catalog = ctx.get_catalog(self.get_table_info().catalog()).await?;
        let table_ids = descendant_ids.iter().copied().collect::<Vec<_>>();
        for (table_id, seq_meta) in catalog.mget_table_metas_by_ids(&table_ids).await? {
            let Some(seq_meta) = seq_meta else {
                continue;
            };
            let mut table_info = self.get_table_info().clone();
            table_info.ident.table_id = table_id;
            table_info.ident.seq = seq_meta.seq;
            table_info.meta = seq_meta.data;
            let descendant = catalog.get_table_by_info(&table_info)?;
            let descendant = FuseTable::try_from_table(descendant.as_ref())?;
            Self::protect_table_tags(descendant, &catalog, segments).await?;
        }
        Ok(())
    }

    /// Get all segments still reachable from this table and its clone descendants.
    #[async_backtrace::framed]
    pub async fn get_snapshot_referenced_segments<T>(
        &self,
        ctx: Arc<dyn TableContext>,
        status_callback: T,
    ) -> Result<Option<HashSet<Location>>>
    where
        T: Fn(String),
    {
        let Some(root_snapshot_location) = self.snapshot_loc() else {
            return Ok(None);
        };
        let mut segments = HashSet::new();
        Self::collect_retained_snapshot_segments(
            self,
            &ctx,
            root_snapshot_location,
            &mut segments,
            &status_callback,
        )
        .await?;

        let catalog = ctx.get_catalog(self.get_table_info().catalog()).await?;
        Self::protect_table_tags(self, &catalog, &mut segments).await?;
        let (descendant_ids, _) = self
            .extend_clone_descendant_referenced_segments(
                ctx.clone(),
                &mut segments,
                status_callback,
            )
            .await?;
        self.extend_clone_descendant_tag_segments(ctx, &descendant_ids, &mut segments)
            .await?;
        Ok(Some(segments))
    }

    pub async fn prepare_snapshot_gc_selection(
        &self,
        ctx: &Arc<dyn TableContext>,
        respect_flash_back: bool,
    ) -> Result<Option<SnapshotGcSelection>> {
        let Some(latest_snapshot) = self.read_table_snapshot().await? else {
            info!(
                "Table {} has no snapshot, stopping vacuum",
                self.table_info.desc
            );
            return Ok(None);
        };

        let start = Instant::now();
        let retention_policy = self.get_data_retention_policy(ctx.as_ref())?;
        let snapshot_location_prefix = self.meta_location_generator().snapshot_location_prefix();

        let mut is_vacuum_all = false;
        let mut respect_flash_back_with_lvt = None;

        let snapshots_before_lvt = match retention_policy {
            RetentionPolicy::ByTimePeriod(delta_duration) => {
                info!("Using ByTimePeriod policy {:?}", delta_duration);
                let retention_period = if self.is_transient() {
                    // For transient table, keep no history data
                    TimeDelta::zero()
                } else {
                    delta_duration
                };

                // A zero retention period indicates that we should vacuum all the historical snapshots
                is_vacuum_all = retention_period.is_zero();

                let Some(lvt) = self
                    .calculate_lvt(latest_snapshot, ctx.as_ref(), retention_period)
                    .await?
                else {
                    return Ok(None);
                };

                respect_flash_back_with_lvt = flashback_gc_root_lvt(respect_flash_back, lvt);

                ctx.set_status_info(&format!(
                    "Set LVT for table {}, elapsed: {:?}, LVT: {:?}",
                    self.table_info.desc,
                    start.elapsed(),
                    lvt
                ));

                if is_vacuum_all {
                    self.list_files_until_prefix(
                        snapshot_location_prefix,
                        self.snapshot_loc().unwrap().as_str(),
                        true,
                        None,
                    )
                    .await?
                } else {
                    self.list_files_until_timestamp(snapshot_location_prefix, lvt, true, None)
                        .await?
                }
            }
            RetentionPolicy::ByNumOfSnapshotsToKeep(num_snapshots_to_keep) => {
                info!(
                    "Using ByNumOfSnapshotsToKeep policy {:?}",
                    num_snapshots_to_keep
                );
                // List the snapshot order by timestamp asc, till the current snapshot(inclusively).
                let need_one_more = true;
                let mut snapshots = self
                    .list_files_until_prefix(
                        snapshot_location_prefix,
                        // Safe to unwrap here: we have checked that `fuse_table` has a snapshot
                        self.snapshot_loc().unwrap().as_str(),
                        need_one_more,
                        None,
                    )
                    .await?;
                let len = snapshots.len();
                if len <= num_snapshots_to_keep {
                    // Only the current snapshot is there, done
                    return Ok(None);
                }
                if num_snapshots_to_keep == 1 {
                    // Expecting only one snapshot left, which means that we can use the current snapshot
                    // as gc root, this flag will be propagated to the select_gc_root func later.
                    is_vacuum_all = true;
                }

                // When selecting the GC root later, the last snapshot in `snapshots` (after truncation)
                // is the candidate, but its commit status is uncertain, so its previous snapshot is used
                // as the GC root instead (except in the is_vacuum_all case).

                // Therefore, during snapshot truncation, we keep 2 extra snapshots;
                // see `select_gc_root` for details.
                let num_candidates = len - num_snapshots_to_keep + 2;
                snapshots.truncate(num_candidates);
                snapshots
            }
        };

        let elapsed = start.elapsed();
        ctx.set_status_info(&format!(
            "Listed snapshots for table {}, elapsed: {:?}, snapshots_dir: {:?}, snapshots: {:?}",
            self.table_info.desc,
            elapsed,
            snapshot_location_prefix,
            slice_summary(&snapshots_before_lvt)
        ));

        let Some(selection) = self
            .select_gc_root(
                ctx,
                &snapshots_before_lvt,
                is_vacuum_all,
                respect_flash_back_with_lvt,
            )
            .await?
        else {
            return Ok(None);
        };

        ctx.set_status_info(&format!(
            "Selected gc_root for table {}, elapsed: {:?}, gc_root: {:?}, snapshots_to_gc: {:?}",
            self.table_info.desc,
            start.elapsed(),
            selection.gc_root,
            slice_summary(&selection.snapshots_to_gc)
        ));
        Ok(Some(selection))
    }

    async fn select_gc_root(
        &self,
        ctx: &Arc<dyn TableContext>,
        snapshots_before_lvt: &[Entry],
        is_vacuum_all: bool,
        respect_flash_back: Option<DateTime<Utc>>,
    ) -> Result<Option<SnapshotGcSelection>> {
        let op = self.get_operator();
        let gc_root_path = if is_vacuum_all {
            // safe to unwrap, or we should have stopped vacuuming in calculate_lvt()
            self.snapshot_loc().unwrap()
        } else if let Some(lvt) = respect_flash_back {
            let latest_location = self.snapshot_loc().unwrap();
            let gc_root = self
                .find_location(ctx, latest_location, |snapshot| {
                    is_snapshot_at_or_before_lvt(snapshot.timestamp, lvt)
                })
                .await
                .ok();
            let Some(gc_root) = gc_root else {
                info!("no gc_root found, stop vacuuming");
                return Ok(None);
            };
            gc_root
        } else {
            if snapshots_before_lvt.is_empty() {
                info!("no snapshots before lvt, stop vacuuming");
                return Ok(None);
            }
            let (anchor, _) = SnapshotsIO::read_snapshot(
                snapshots_before_lvt.last().unwrap().path().to_owned(),
                op.clone(),
                false,
            )
            .await?;
            let Some((gc_root_id, gc_root_ver)) = anchor.prev_snapshot_id else {
                info!("anchor has no prev_snapshot_id, stop vacuuming");
                return Ok(None);
            };
            let gc_root_path = self
                .meta_location_generator()
                .gen_snapshot_location(&gc_root_id, gc_root_ver)?;
            if !is_uuid_v7(&gc_root_id) {
                info!("gc_root {} is not v7", gc_root_path);
                return Ok(None);
            }
            gc_root_path
        };

        let dal = self.get_operator_ref();
        let gc_root = SnapshotsIO::read_snapshot(gc_root_path.clone(), op.clone(), false).await;
        let gc_root_meta_ts = match dal.stat(&gc_root_path).await {
            Ok(v) => v.last_modified().ok_or_else(|| {
                ErrorCode::StorageOther(format!(
                    "Failed to get `last_modified` metadata of the gc root object '{}'",
                    gc_root_path
                ))
            })?,
            Err(e) => {
                return if e.kind() == ErrorKind::NotFound {
                    // Concurrent vacuum, ignore it
                    Ok(None)
                } else {
                    Err(e.into())
                };
            }
        };
        let gc_root_meta_ts = DateTime::<Utc>::from(SystemTime::from(gc_root_meta_ts));

        match gc_root {
            Ok((gc_root, _)) => {
                info!("gc_root found: {:?}", gc_root);
                let mut gc_candidates = Vec::with_capacity(snapshots_before_lvt.len());

                for snapshot in snapshots_before_lvt.iter() {
                    let path = snapshot.path();
                    let last_part = path.rsplit('/').next().unwrap();
                    if last_part.starts_with(VACUUM2_OBJECT_KEY_PREFIX) {
                        gc_candidates.push(path.to_owned());
                    } else {
                        // This snapshot is created by a node of the previous version which does not
                        // support vacuum2, we rely on the `ASSUMPTION_MAX_TXN_DURATION` to identify if
                        // it is available to be vacuumed.
                        let last_modified = match snapshot.metadata().last_modified() {
                            None => dal.stat(path).await?.last_modified().ok_or_else(|| {
                                ErrorCode::StorageOther(format!(
                                    "Failed to get `last_modified` metadata of the snapshot object '{}'",
                                    gc_root_path
                                ))
                            })?,
                            Some(v) => v,
                        };
                        let last_modified = DateTime::<Utc>::from(SystemTime::from(last_modified));
                        if last_modified + ASSUMPTION_MAX_TXN_DURATION < gc_root_meta_ts {
                            gc_candidates.push(path.to_owned());
                        }
                    }
                }

                let gc_root_idx = gc_candidates.binary_search(&gc_root_path).map_err(|_| {
                    ErrorCode::Internal(format!(
                        "gc root path {} should be one of the candidates, candidates: {:?}",
                        gc_root_path, gc_candidates
                    ))
                })?;
                let snapshots_to_gc = gc_candidates[..gc_root_idx].to_vec();
                let lvt = LeastVisibleTime::new(gc_root.timestamp.unwrap());
                Ok(Some(SnapshotGcSelection {
                    gc_root,
                    snapshots_to_gc,
                    gc_root_meta_ts,
                    gc_root_path,
                    lvt,
                }))
            }
            Err(e) => {
                info!("read gc_root {} failed: {:?}", gc_root_path, e);
                Ok(None)
            }
        }
    }

    /// Calculate this table's LVT candidate without publishing it.
    pub async fn calculate_lvt(
        &self,
        latest_snapshot: Arc<TableSnapshot>,
        ctx: &dyn TableContext,
        retention_period: TimeDelta,
    ) -> Result<Option<DateTime<Utc>>> {
        if !is_uuid_v7(&latest_snapshot.snapshot_id) {
            info!(
                "Latest snapshot is not v7, stopping vacuum: {:?}",
                latest_snapshot.snapshot_id
            );
            return Ok(None);
        }
        let catalog = ctx.get_default_catalog()?;
        // safe to unwrap, as we have checked the version is v4
        let latest_ts = latest_snapshot.timestamp.unwrap();
        let lvt_point_candidate = retention_cutoff(Utc::now(), latest_ts, retention_period);
        let current = catalog
            .get_table_lvt(&LeastVisibleTimeIdent::new(ctx.get_tenant(), self.get_id()))
            .await?
            .map(|lvt| lvt.time);
        Ok(Some(current.map_or(lvt_point_candidate, |time| {
            max(time, lvt_point_candidate)
        })))
    }
}

pub async fn vacuum_tables_from_info(
    table_infos: Vec<TableInfo>,
    ctx: Arc<dyn TableContext>,
    vacuum_handler: Arc<VacuumHandlerWrapper>,
) -> Result<()> {
    for table_info in table_infos {
        let table = FuseTable::create_without_refresh_table_info(
            table_info,
            ctx.get_settings().get_s3_storage_class()?,
        )?
        .refresh(ctx.as_ref())
        .await?;
        let fuse_table = FuseTable::try_from_table(table.as_ref())?;
        fuse_table
            .vacuum_table(ctx.clone(), &vacuum_handler, true)
            .await;
    }

    Ok(())
}

pub fn slice_summary<T: std::fmt::Debug>(s: &[T]) -> String {
    if s.len() > 10 {
        let first_five = &s[..5];
        let last_five = &s[s.len() - 5..];
        format!(
            "First five: {:?}, Last five: {:?},Len: {}",
            first_five,
            last_five,
            s.len()
        )
    } else {
        format!("{:?}", s)
    }
}

#[cfg(test)]
mod tests {
    use chrono::TimeZone;

    use super::*;

    #[test]
    fn test_retention_cutoff_is_bounded_by_latest_snapshot() {
        let now = Utc.with_ymd_and_hms(2025, 1, 10, 12, 0, 0).unwrap();
        let retention_period = TimeDelta::days(2);

        // When the latest snapshot is newer than the retention boundary, use
        // now - retention as the cutoff.
        let latest_after_cutoff = Utc.with_ymd_and_hms(2025, 1, 9, 12, 0, 0).unwrap();
        assert_eq!(
            retention_cutoff(now, latest_after_cutoff, retention_period),
            Utc.with_ymd_and_hms(2025, 1, 8, 12, 0, 0).unwrap()
        );

        // The cutoff must not move past the latest snapshot. This also keeps
        // the result valid when the host clock is ahead of snapshot time.
        let latest_before_cutoff = Utc.with_ymd_and_hms(2025, 1, 7, 12, 0, 0).unwrap();
        assert_eq!(
            retention_cutoff(now, latest_before_cutoff, retention_period),
            latest_before_cutoff
        );
    }

    #[test]
    fn test_snapshot_at_or_before_lvt_boundary() {
        let lvt = Utc.with_ymd_and_hms(2025, 1, 8, 12, 0, 0).unwrap();

        assert_eq!(flashback_gc_root_lvt(false, lvt), None);
        assert_eq!(flashback_gc_root_lvt(true, lvt), Some(lvt));
        assert!(!is_snapshot_at_or_before_lvt(None, lvt));
        assert!(!is_snapshot_at_or_before_lvt(
            Some(lvt + TimeDelta::microseconds(1)),
            lvt
        ));
        assert!(is_snapshot_at_or_before_lvt(Some(lvt), lvt));
        assert!(is_snapshot_at_or_before_lvt(
            Some(lvt - TimeDelta::microseconds(1)),
            lvt
        ));
    }

    #[test]
    fn test_clone_descendant_ids_detects_new_descendant() {
        let initial = vec![(2, 1), (3, 2), (4, 1)];
        assert_eq!(
            FuseTable::clone_descendant_ids(1, 1, &initial).unwrap(),
            HashSet::from([2, 3, 4])
        );
        let observed = FuseTable::clone_descendant_ids(1, 2, &initial).unwrap();
        assert_eq!(observed, HashSet::from([3]));

        let mut changed = initial;
        changed.push((5, 3));
        let current = FuseTable::clone_descendant_ids(1, 2, &changed).unwrap();
        assert_eq!(current, HashSet::from([3, 5]));
        assert!(!current.is_subset(&observed));
    }

    #[test]
    fn test_clone_descendant_ids_rejects_disconnected_lineage() {
        let err = FuseTable::clone_descendant_ids(1, 1, &[(2, 1), (4, 3)]).unwrap_err();
        assert_eq!(err.code(), ErrorCode::INTERNAL);
    }
}
